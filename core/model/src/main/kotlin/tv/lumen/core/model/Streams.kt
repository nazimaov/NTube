package tv.lumen.core.model

import java.time.Instant

/** Полные данные для экрана просмотра (SPEC 4.3, 4.4). */
data class VideoDetails(
    val video: Video,
    val description: String,
    /** -1, если неизвестно. */
    val likeCount: Long,
    val channelAvatarUrl: String?,
    /** -1, если неизвестно. */
    val channelSubscriberCount: Long,
    val ageLimit: Int,
    val streams: StreamSet,
    val related: List<Video>,
    val fetchedAt: Instant,
)

/** Все потоки видео в собственной модели; классы экстрактора наружу не выходят. */
data class StreamSet(
    /** Видео без звука — основной путь (до 4K/8K). */
    val videoOnly: List<VideoStream>,
    /** Отдельные аудиодорожки. */
    val audio: List<AudioStream>,
    /** Видео со звуком в одном файле, обычно до 360p — запасной путь. */
    val muxed: List<VideoStream>,
    val subtitles: List<SubtitleTrack>,
    /** Манифест прямого эфира. */
    val hlsUrl: String?,
    val dashMpdUrl: String?,
    val isLive: Boolean,
    val durationSec: Long,
) {
    val maxVideoHeight: Int get() = (videoOnly + muxed).maxOfOrNull { it.height } ?: 0
}

enum class DeliveryMethod {
    /** Прямая ссылка на файл. */
    PROGRESSIVE_HTTP,
    /** Нужен DASH-манифест: получить через репозиторий источника. */
    DASH,
    HLS,
    OTHER,
}

enum class VideoCodec { AV1, VP9, AVC, OTHER }

enum class AudioCodec { OPUS, AAC, OTHER }

data class VideoStream(
    /** Уникален в пределах одного видео (itag). */
    val id: String,
    val url: String,
    val delivery: DeliveryMethod,
    val mimeType: String?,
    val codec: VideoCodec,
    /** Строка кодека как в mime (например, `vp09.00.51.08`). */
    val codecString: String?,
    val width: Int,
    val height: Int,
    val fps: Int,
    val bitrate: Int,
    val isHdr: Boolean,
    /** Подпись качества от YouTube (`1080p60`, `2160p HDR`). */
    val qualityLabel: String?,
)

data class AudioStream(
    val id: String,
    val url: String,
    val delivery: DeliveryMethod,
    val mimeType: String?,
    val codec: AudioCodec,
    val codecString: String?,
    val bitrate: Int,
    /** Идентификатор дорожки при нескольких языках; null — единственная дорожка. */
    val trackId: String?,
    val trackName: String?,
    /** Тег языка BCP 47, если известен. */
    val language: String?,
    /** true — оригинальная дорожка (не дубляж и не тифлокомментарий). */
    val isOriginal: Boolean,
)

data class SubtitleTrack(
    val url: String,
    val languageTag: String,
    val name: String,
    val isAutoGenerated: Boolean,
    val mimeType: String?,
)
