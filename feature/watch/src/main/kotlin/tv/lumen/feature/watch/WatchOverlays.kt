private val SPEEDS = listOf(0.25f, 0.5f, 0.75f, 1f, 1.25f, 1.5f, 1.75f, 2f, 2.5f, 3f)

private data class Option(val label: String, val selected: Boolean, val onSelect: () -> Unit)

@Composable
internal fun OptionsDialog(
    dialog: WatchDialog,
    state: PlayerState,
    controller: PlayerController,
    onDismiss: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val title: String
    val options: List<Option>
    when (dialog) {
        WatchDialog.QUALITY -> {
            title = stringResource(R.string.watch_quality)
            options = state.qualities.map { q ->
                Option(q.label, q.height == state.quality?.height) { controller.setQuality(q.height) }
            }
        }
        WatchDialog.SPEED -> {
            title = stringResource(R.string.watch_speed)
            options = SPEEDS.map { s -> Option(formatSpeed(s), s == state.speed) { controller.setSpeed(s) } } +
                if (state.isSubscribed) {
                    listOf(Option(stringResource(R.string.watch_speed_remember, formatSpeed(state.speed)), false) { controller.rememberSpeedForChannel() })
                } else {
                    emptyList()
                }
        }
        WatchDialog.SUBTITLES -> {
            title = stringResource(R.string.watch_subtitles)
            val auto = stringResource(R.string.watch_auto_generated)
            options = listOf(Option(stringResource(R.string.watch_subtitles_off), state.subtitle == null) { controller.setSubtitle(null) }) +
                state.subtitles.distinctBy { it.languageTag + it.isAutoGenerated }.map { t ->
                    val label = if (t.isAutoGenerated) "${t.name} ($auto)" else t.name
                    Option(label, t.languageTag == state.subtitle) { controller.setSubtitle(t.languageTag) }
                }
        }
        WatchDialog.AUDIO -> {
            title = stringResource(R.string.watch_audio)
            val original = stringResource(R.string.watch_audio_original)
            options = state.audioTracks.map { t ->
                val label = if (t.isOriginal) "${t.name} ($original)" else t.name
                Option(label, t.id == state.audioTrack) { controller.setAudioTrack(t.id) }
            }
        }
    }

    val selectedIndex = options.indexOfFirst { it.selected }.coerceAtLeast(0)
    val focus = remember { FocusRequester() }
    LaunchedEffect(dialog) { runCatching { focus.requestFocus() } }

    Column(
        modifier = modifier
            .fillMaxHeight()
            .width(360.dp)
            .background(Color(0xF01A1A1A))
            .padding(vertical = LumenDimens.SafeVertical, horizontal = 24.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        Text(title, style = MaterialTheme.typography.headlineSmall, color = Color.White)
        LazyColumn(verticalArrangement = Arrangement.spacedBy(4.dp)) {
            itemsIndexed(options) { index, option ->
                ListItem(
                    selected = option.selected,
                    onClick = {
                        option.onSelect()
                        onDismiss()
                    },
                    headlineContent = { Text(option.label) },
                    modifier = if (index == selectedIndex) Modifier.focusRequester(focus) else Modifier,
                )
            }
        }
    }
}

@Composable
internal fun ErrorOverlay(error: AppError, onRetry: () -> Unit, onCheckUpdate: () -> Unit, modifier: Modifier = Modifier) {
    val focus = remember { FocusRequester() }
    LaunchedEffect(error) { runCatching { focus.requestFocus() } }
    Column(
        modifier = modifier
            .width(720.dp)
            .background(Color.Black.copy(alpha = 0.8f), RoundedCornerShape(16.dp))
            .padding(32.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(24.dp),
    ) {
        Text(errorText(error), style = MaterialTheme.typography.titleLarge, color = Color.White)
        androidx.compose.foundation.layout.Row(horizontalArrangement = Arrangement.spacedBy(16.dp)) {
            Button(onClick = onRetry, modifier = Modifier.focusRequester(focus)) {
                Text(stringResource(R.string.watch_retry))
            }
            // ExtractionBroken — экстрактор устарел, починка в новой версии приложения
            if (error == AppError.ExtractionBroken) {
                Button(onClick = onCheckUpdate) { Text(stringResource(R.string.watch_check_update)) }
            }
        }
    }
}

@Composable
private fun errorText(error: AppError): String = stringResource(
    when (error) {
        AppError.Network -> R.string.watch_error_network
        AppError.ExtractionBroken -> R.string.watch_error_extraction
        AppError.AgeRestricted -> R.string.watch_error_age
        is AppError.ContentUnavailable -> when (error.reason) {
            UnavailableReason.PRIVATE -> R.string.watch_error_private
            UnavailableReason.GEO_BLOCKED -> R.string.watch_error_geo
            UnavailableReason.PAID -> R.string.watch_error_paid
            UnavailableReason.BOT_CHECK -> R.string.watch_error_bot
            else -> R.string.watch_error_unavailable
        }
        is AppError.Unknown -> R.string.watch_error_unknown
    },
)
