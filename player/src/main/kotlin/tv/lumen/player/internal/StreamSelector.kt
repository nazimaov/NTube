package tv.lumen.player.internal

import tv.lumen.core.model.AudioCodec
import tv.lumen.core.model.AudioStream
import tv.lumen.core.model.DeliveryMethod
import tv.lumen.core.model.StreamSet
import tv.lumen.core.model.SubtitleTrack
import tv.lumen.core.model.VideoCodec
import tv.lumen.core.model.VideoStream
import tv.lumen.player.AudioTrackOption
import tv.lumen.player.CodecPreference
import tv.lumen.player.PlayerPreferences
import tv.lumen.player.QualityOption

/** Возможности устройства, от которых зависит выбор потока. */
internal interface DeviceCapabilities {
    /** Высота дисплея в пикселях; 0 — неизвестна. */
    val displayHeight: Int
    val hdrSupported: Boolean

    /** Есть ли на устройстве хоть один аппаратный видеодекодер нужных кодеков. */
    val hasHardwareVideoDecoders: Boolean

    fun canDecode(codec: VideoCodec, width: Int, height: Int, fps: Int, allowSoftware: Boolean): Boolean
}

internal sealed interface Selection {
    data class Separate(
        val video: VideoStream,
        val audio: AudioStream,
        val qualities: List<QualityOption>,
        val audioTracks: List<AudioTrackOption>,
    ) : Selection

    /** Видео со звуком в одном файле (обычно 360p): отдельных потоков нет или ни один не декодируется. */
    data class Muxed(val stream: VideoStream, val lowQualityNotice: Boolean) : Selection

    data class Live(val hlsUrl: String?, val dashMpdUrl: String?) : Selection

    /** Только звук (режим «аудио» в музыке): без видеопотока, экономит трафик. */
    data class AudioOnly(val audio: AudioStream) : Selection

    data object Unplayable : Selection
}

/** Правила выбора качества (SPEC 5.3). Чистая логика без Android — покрыта модульными тестами. */
internal class StreamSelector(private val caps: DeviceCapabilities) {

    fun select(
        set: StreamSet,
        prefs: PlayerPreferences,
        requestedHeight: Int? = null,
        audioTrackId: String? = null,
        audioOnly: Boolean = false,
    ): Selection {
        if (set.isLive && (set.hlsUrl != null || set.dashMpdUrl != null)) {
            return Selection.Live(set.hlsUrl, set.dashMpdUrl)
        }
        if (audioOnly) selectAudio(set.audio, prefs, audioTrackId)?.let { return Selection.AudioOnly(it) }

        val playable = playableVideo(set.videoOnly, prefs)
        val audio = selectAudio(set.audio, prefs, audioTrackId)
        if (playable.isNotEmpty() && audio != null) {
            val maxHeight = requestedHeight ?: maxHeight(prefs)
            val video = playable.filter { it.height <= maxHeight }.maxWithOrNull(videoOrder)
                ?: playable.minBy { it.height }
            return Selection.Separate(video, audio, qualities(playable), audioTracks(set.audio))
        }

        val muxed = set.muxed.filter { it.delivery == DeliveryMethod.PROGRESSIVE_HTTP }.maxByOrNull { it.height }
            ?: return Selection.Unplayable
        return Selection.Muxed(muxed, lowQualityNotice = set.videoOnly.isEmpty() || audio == null)
    }

    fun maxHeight(prefs: PlayerPreferences): Int =
        prefs.maxResolution.takeIf { it > 0 } ?: caps.displayHeight.takeIf { it > 0 } ?: DEFAULT_MAX_HEIGHT

    /**
     * Потоки, которые устройство может декодировать. Программные декодеры используются только там,
     * где аппаратных нет вообще (эмулятор) — см. docs/DECISIONS.md.
     */
    fun playableVideo(streams: List<VideoStream>, prefs: PlayerPreferences): List<VideoStream> {
        val allowSoftware = !caps.hasHardwareVideoDecoders
        val decodable = streams.filter { s ->
            s.delivery.isSupported() &&
                s.codec != VideoCodec.OTHER &&
                (!s.isHdr || caps.hdrSupported) &&
                caps.canDecode(s.codec, s.width, s.height, s.fps, allowSoftware)
        }
        val wanted = prefs.preferredCodec.toCodec() ?: return decodable
        return decodable.filter { it.codec == wanted }.ifEmpty { decodable }
    }

    fun selectAudio(streams: List<AudioStream>, prefs: PlayerPreferences, trackId: String?): AudioStream? {
        val usable = streams.filter { it.delivery.isSupported() }
        if (usable.isEmpty()) return null
        val byTrack = when {
            trackId != null -> usable.filter { it.trackId == trackId }
            prefs.audioLanguage != null -> usable.filter { it.language?.startsWith(prefs.audioLanguage) == true }
            else -> usable.filter { it.isOriginal }
        }.ifEmpty { usable.filter { it.isOriginal } }.ifEmpty { usable }
        return byTrack.maxWith(compareBy<AudioStream> { it.codec == AudioCodec.OPUS }.thenBy { it.bitrate })
    }

    fun selectSubtitle(tracks: List<SubtitleTrack>, lang: String?): SubtitleTrack? {
        if (lang == null) return null
        val matching = tracks.filter { it.languageTag == lang }.ifEmpty { tracks.filter { it.languageTag.startsWith(lang) } }
        return matching.firstOrNull { !it.isAutoGenerated } ?: matching.firstOrNull()
    }

    private fun qualities(playable: List<VideoStream>): List<QualityOption> =
        playable.groupBy { it.height }
            .map { (_, sameHeight) -> sameHeight.maxWith(videoOrder) }
            .sortedByDescending { it.height }
            .map { QualityOption(it.height, it.fps, it.codec) }

    private fun audioTracks(streams: List<AudioStream>): List<AudioTrackOption> =
        streams.mapNotNull { s -> s.trackId?.let { AudioTrackOption(it, s.trackName ?: s.language ?: it, s.isOriginal) } }
            .distinctBy { it.id }

    private fun DeliveryMethod.isSupported() = this == DeliveryMethod.PROGRESSIVE_HTTP || this == DeliveryMethod.DASH

    private fun CodecPreference.toCodec(): VideoCodec? = when (this) {
        CodecPreference.AUTO -> null
        CodecPreference.AV1 -> VideoCodec.AV1
        CodecPreference.VP9 -> VideoCodec.VP9
        CodecPreference.AVC -> VideoCodec.AVC
    }

    companion object {
        const val DEFAULT_MAX_HEIGHT = 1080

        /** Выше разрешение → выше частота кадров → AV1 → VP9 → AVC → выше битрейт. */
        val videoOrder: Comparator<VideoStream> = compareBy<VideoStream> { it.height }
            .thenBy { it.fps }
            .thenBy { codecRank(it.codec) }
            .thenBy { it.bitrate }

        private fun codecRank(codec: VideoCodec) = when (codec) {
            VideoCodec.AV1 -> 3
            VideoCodec.VP9 -> 2
            VideoCodec.AVC -> 1
            VideoCodec.OTHER -> 0
        }
    }
}
